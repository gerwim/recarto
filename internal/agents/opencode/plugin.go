package opencode

import "strings"

// pluginTemplate is the generated OpenCode plugin. Backticks are written as "~"
// and substituted at generation time (Go raw strings cannot contain backticks);
// __BIN__ is replaced with a JS string literal of the recarto binary path.
//
// The plugin bridges OpenCode lifecycle hooks to `recarto hook … --agent opencode`,
// feeding a neutral JSON payload on stdin (via Bun's `<` Response redirection) and
// applying the neutral JSON result. Every hook is defensive: unknown payload
// shapes degrade to a no-op so the plugin never breaks an OpenCode session.
const pluginTemplate = `// recarto OpenCode plugin — generated by ` + "`recarto init`" + `. Do not edit by hand.
// Bridges OpenCode lifecycle hooks to the recarto binary.
const BIN = __BIN__;

export const recarto = async ({ $, directory }) => {
  const run = async (event, payload) => {
    try {
      const r = await $~${BIN} hook ${event} --agent opencode < ${new Response(JSON.stringify(payload || {}))}~
        .cwd(directory).quiet().nothrow();
      return JSON.parse(r.stdout.toString() || "{}");
    } catch (e) {
      return {};
    }
  };

  let injected = false;
  const pathOf = (x) => (x && (x.file || x.path || x.filePath || (x.properties && x.properties.file))) || "";

  return {
    // Inject this branch's recalled memory into the system prompt once per session.
    "experimental.chat.system.transform": async (_input, output) => {
      if (injected) return;
      injected = true;
      const r = await run("session-start", {});
      if (r && r.additionalContext && output && Array.isArray(output.system)) {
        output.system.push(r.additionalContext);
      }
    },

    // Re-index a file right after the agent edits it (side effect; no injection).
    "file.edited": async (input) => {
      const fp = pathOf(input);
      if (fp) await run("post-edit", { file_path: fp });
    },

    // After a search/read tool, append recarto's advisory context to the result.
    "tool.execute.after": async (input, output) => {
      const name = (input && (input.tool || input.name)) || "";
      const args = (output && output.args) || (input && input.args) || {};
      if (/grep|glob|search|find/i.test(name)) {
        const r = await run("augment", { pattern: args.pattern || args.query || "" });
        if (r && r.additionalContext && output) output.output = (output.output || "") + "\n\n" + r.additionalContext;
      } else if (/read|view|cat/i.test(name)) {
        const r = await run("post-read", { file_path: args.filePath || args.path || "", tool_result: (output && output.output) || "" });
        if (r && r.additionalContext && output) output.output = (output.output || "") + "\n\n" + r.additionalContext;
      }
    },
  };
};
`

// pluginJS returns the generated plugin source bound to the recarto binary path.
func pluginJS(binary string) string {
	js := strings.ReplaceAll(pluginTemplate, "~", "`")
	return strings.ReplaceAll(js, "__BIN__", jsString(binary))
}

// jsString returns a JSON-style double-quoted JS string literal, safe for Windows
// paths (backslashes) and quotes.
func jsString(s string) string {
	q := strings.ReplaceAll(s, `\`, `\\`)
	q = strings.ReplaceAll(q, `"`, `\"`)
	return `"` + q + `"`
}
