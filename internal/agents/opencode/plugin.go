package opencode

import "strings"

// pluginTemplate is the generated OpenCode plugin; __BIN__ is replaced with a JS
// string literal of the recarto binary path.
//
// One default export serves both OpenCode plugin APIs: OpenCode 2 loads
// {id, setup} and calls setup(ctx), registering hooks on the context's domains;
// OpenCode 1 calls server() for its string-keyed hooks. Both bridge to
// `recarto hook … --agent opencode`, feeding a neutral JSON payload on stdin and
// applying the neutral JSON result. Every hook is defensive: failures and
// unknown shapes degrade to a no-op so the plugin never breaks a session.
const pluginTemplate = `// recarto OpenCode plugin — generated by "recarto init". Do not edit by hand.
// Bridges OpenCode lifecycle hooks to the recarto binary. The default export
// serves both plugin APIs: OpenCode 2 calls setup(ctx), OpenCode 1 calls server().
import { spawn } from "node:child_process";
import { resolve } from "node:path";

const BIN = __BIN__;

// SHELL_COMMANDS spots a shell line that may search or print files (grep,
// egrep, fgrep, rg, ugrep, git grep, find, bfs, cat, head, tail, sed); recarto
// reads it, and any other line never starts recarto.
const SHELL_COMMANDS = /\b(grep|egrep|fgrep|rg|ugrep|find|bfs|cat|head|tail|sed)\b/;
const isShell = (tool, command) => (tool === "bash" || tool === "shell") && SHELL_COMMANDS.test(command || "");

// run pipes a neutral JSON payload to "recarto hook <event> --agent opencode" and
// resolves its JSON result. Any failure (missing binary, bad output, a hook
// wedged past a minute) resolves {} so recarto never breaks a session.
const run = (cwd, event, payload) =>
  new Promise((done) => {
    let out = "";
    try {
      const child = spawn(BIN, ["hook", event, "--agent", "opencode"], { cwd, stdio: ["pipe", "pipe", "ignore"], windowsHide: true });
      const timer = setTimeout(() => child.kill(), 60000);
      child.stdout.on("data", (d) => (out += d));
      child.stdin.on("error", () => {});
      child.on("error", () => done({}));
      child.on("close", () => {
        clearTimeout(timer);
        try {
          done(JSON.parse(out || "{}") || {});
        } catch {
          done({});
        }
      });
      child.stdin.end(JSON.stringify(payload));
    } catch {
      done({});
    }
  });

// sessionStarts memoises the session-start context per session: hosts apply it
// to every model request (system-prompt edits are not persisted), but recarto
// runs once per session.
const sessionStarts = (cwd) => {
  const seen = new Map();
  return (sessionID = "") => {
    if (!seen.has(sessionID)) seen.set(sessionID, run(cwd, "session-start", { session_id: sessionID }));
    return seen.get(sessionID);
  };
};

// contentOf returns an OpenCode 2 tool result's model-facing content as parts,
// normalized the way OpenCode does (falling back to the structured output).
const contentOf = (r) =>
  typeof r.content === "string"
    ? [{ type: "text", text: r.content }]
    : Array.isArray(r.content) && r.content.length > 0
      ? [...r.content]
      : [{ type: "text", text: typeof r.output === "string" ? r.output : JSON.stringify(r.output) || "" }];

// OpenCode 2 plugin API.
const setup = async (ctx) => {
  const dir = ctx.location.directory;
  const abs = (p) => (p ? resolve(dir, p) : "");
  const start = sessionStarts(dir);
  const append = (event, text) => {
    if (text) event.result = { ...event.result, content: [...contentOf(event.result), { type: "text", text }] };
  };

  // Inject this branch's recalled memory into every agent request of a session.
  await ctx.session.hook("context", async (event) => {
    try {
      const r = await start(event.sessionID);
      if (r.additionalContext) event.system.push({ type: "text", text: r.additionalContext });
    } catch {}
  });

  // After a built-in read/search/edit/shell tool, append recarto's advisory
  // context to the result the model sees; edits also re-index the changed files.
  await ctx.tool.hook("execute.after", async (event) => {
    try {
      if (event.status !== "completed") return;
      const input = event.input || {};
      const base = { session_id: event.sessionID };
      if (event.tool === "read") {
        if (event.result.output && event.result.output.type === "list-page") return; // a directory listing
        const text = contentOf(event.result).map((c) => c.text || "").join("\n");
        append(event, (await run(dir, "post-read", { ...base, file_path: abs(input.path), tool_result: text, offset: input.offset, limit: input.limit })).additionalContext);
      } else if (event.tool === "grep" || event.tool === "glob") {
        append(event, (await run(dir, "augment", { ...base, pattern: input.pattern || "" })).additionalContext);
      } else if (isShell(event.tool, input.command)) {
        append(event, (await run(dir, "shell", { ...base, command: input.command, cwd: abs(input.workdir) || dir })).additionalContext);
      } else if (event.tool === "edit" || event.tool === "write" || event.tool === "patch") {
        const applied = (event.result.output && event.result.output.applied) || [];
        const files = event.tool === "patch" ? applied.map((a) => a.target) : [abs(input.path)];
        const notes = [];
        for (const file of files) {
          const r = await run(dir, "post-edit", { ...base, file_path: file });
          if (r.additionalContext) notes.push(r.additionalContext);
        }
        append(event, notes.join("\n"));
      }
    } catch {}
  });

  // When a turn of a root session here completes, run the stop hook (closes the
  // session, flushes sync); its once-per-session capture nudge goes back to the
  // model as a synthetic message, like Claude Code's block-once Stop.
  const stop = async (sessionID) => {
    try {
      const session = await ctx.session.get({ sessionID });
      if (session.parentID || (session.location && session.location.directory !== dir)) return;
      const r = await run(dir, "stop", { session_id: sessionID });
      if (r.decision === "block" && r.reason) await ctx.session.synthetic({ sessionID, text: r.reason });
    } catch {}
  };
  const events = new AbortController();
  (async () => {
    for await (const e of ctx.event.subscribe({ signal: events.signal })) {
      if (e.type === "session.execution.succeeded" && e.data) stop(e.data.sessionID);
    }
  })().catch(() => {});
  return () => events.abort();
};

// OpenCode 1 plugin API.
const server = async ({ directory }) => {
  const abs = (p) => (p ? resolve(directory, p) : "");
  const start = sessionStarts(directory);
  return {
    // Inject this branch's recalled memory into the system prompt of each request.
    "experimental.chat.system.transform": async (input, output) => {
      try {
        const r = await start(input && input.sessionID);
        if (r.additionalContext && output && Array.isArray(output.system)) output.system.push(r.additionalContext);
      } catch {}
    },

    // Re-index a file right after the agent edits it (side effect; no injection).
    event: async ({ event }) => {
      try {
        if (event && event.type === "file.edited" && event.properties && event.properties.file) {
          await run(directory, "post-edit", { file_path: abs(event.properties.file) });
        }
      } catch {}
    },

    // After a read/search/shell tool, append recarto's advisory context to the result.
    "tool.execute.after": async (input, output) => {
      try {
        const args = (input && input.args) || (output && output.args) || {};
        const base = { session_id: input.sessionID };
        let r = {};
        if (input.tool === "read") {
          r = await run(directory, "post-read", { ...base, file_path: abs(args.filePath), tool_result: (output && output.output) || "", offset: args.offset, limit: args.limit });
        } else if (input.tool === "grep" || input.tool === "glob") {
          r = await run(directory, "augment", { ...base, pattern: args.pattern || "" });
        } else if (isShell(input.tool, args.command)) {
          r = await run(directory, "shell", { ...base, command: args.command, cwd: abs(args.workdir) || directory });
        }
        if (r.additionalContext && output) output.output = (output.output || "") + "\n\n" + r.additionalContext;
      } catch {}
    },
  };
};

export default { id: "recarto", setup, server };
`

// pluginJS returns the generated plugin source bound to the recarto binary path.
func pluginJS(binary string) string {
	return strings.ReplaceAll(pluginTemplate, "__BIN__", jsString(binary))
}

// jsString returns a JSON-style double-quoted JS string literal, safe for Windows
// paths (backslashes) and quotes.
func jsString(s string) string {
	q := strings.ReplaceAll(s, `\`, `\\`)
	q = strings.ReplaceAll(q, `"`, `\"`)
	return `"` + q + `"`
}
